# -*- coding: utf-8 -*-
"""Optional OFFLINE label QA previews (not QGIS/OSM maps). Requires matplotlib.
The actual SCI map layouts are generated by 01_BUILD_COMPLETE_QGIS322.py in QGIS.
"""
from pathlib import Path
import sqlite3
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib import patheffects
from matplotlib.lines import Line2D
from matplotlib.patches import Rectangle

ROOT=Path(__file__).resolve().parent.parent
OUT=ROOT/'figures'
OUT.mkdir(exist_ok=True)
con=sqlite3.connect(str(ROOT/'data'/'CIQ_ABC_FINAL_EDITABLE.gpkg'))
con.row_factory=sqlite3.Row
records=[]
for table,codecol,zone in [('V7_ALL_62_RETAINED_ROLES','id',None),
                            ('V8_CIQ_PORT_6_EVIDENCE_POINTS','node_id','A_PORT'),
                            ('G_CIQ_ground_gateway','id','CIQ_GROUND')]:
    for r in con.execute('SELECT * FROM "'+table+'"'):
        records.append(dict(code=r[codecol],name=r['name'],zone=zone or r['zone'],x=r['lon'],y=r['lat']))
con.close()
assert len(records)==69

limits={'A':(103.729,103.858,1.444,1.560),
        'C':(103.574,103.769,1.386,1.571),
        'B':(103.529,103.698,1.326,1.470)}
colors={'A':'#148a85','A_PORT':'#23795a','CIQ_GROUND':'#383d48','C':'#cb8845','B':'#416ba9'}

for zone in ['A','C','B']:
    subset=[r for r in records if r['zone']==zone or (zone=='A' and r['zone'] in ('A_PORT','CIQ_GROUND'))]
    subset.sort(key=lambda r:r['code'])
    fig=plt.figure(figsize=(16.54,11.69),facecolor='white')
    ax=fig.add_axes([.055,.13,.65,.77])
    ax.set_xlim(limits[zone][0],limits[zone][1])
    ax.set_ylim(limits[zone][2],limits[zone][3])
    ax.set_aspect('equal',adjustable='box')
    ax.set_facecolor('#f7f9fa')
    ax.grid(color='#dfe5e9',lw=.6)
    ax.set_xlabel('Longitude (°E)',fontsize=9)
    ax.set_ylabel('Latitude (°N)',fontsize=9)
    ax.tick_params(labelsize=8)
    # Greedy label collision minimization for short IDs only.
    xmin,xmax,ymin,ymax=limits[zone]
    occupied=[]
    for r in sorted(subset,key=lambda a:(a['y'],-a['x']),reverse=True):
        xx=(r['x']-xmin)/(xmax-xmin)
        yy=(r['y']-ymin)/(ymax-ymin)
        ax.scatter([r['x']],[r['y']],s=36,c=colors[r['zone']],edgecolors='white',linewidths=.7,zorder=4)
        offsets=[(.013,.009),(.013,-.011),(-.075,.010),(-.075,-.012),(.01,.026),(-.08,.025),(.015,-.028),(-.08,-.027)]
        def overlap(px,py):
            rect=(px,py,px+.058,py+.018)
            overlap_area=sum(max(0,min(rect[2],q[2])-max(rect[0],q[0]))*max(0,min(rect[3],q[3])-max(rect[1],q[1])) for q in occupied)
            outside=max(0,-rect[0])+max(0,rect[2]-1)+max(0,-rect[1])+max(0,rect[3]-1)
            return overlap_area*1000+outside*20
        dx,dy=min(offsets,key=lambda o:overlap(xx+o[0],yy+o[1]))
        tx,ty=xx+dx,yy+dy
        occupied.append((tx,ty,tx+.058,ty+.018))
        ax.annotate(r['code'],(r['x'],r['y']),xytext=(tx,ty),textcoords='axes fraction',
                    fontsize=8,fontweight='bold',color='#20252a',ha='left',va='bottom',
                    arrowprops=dict(arrowstyle='-',color='#858f99',lw=.5,shrinkA=2,shrinkB=3),
                    path_effects=[patheffects.withStroke(linewidth=2,foreground='white')],zorder=6)
    fig.text(.055,.953,'CIQ GIS | '+zone+' region — all node IDs',fontsize=20,weight='bold',color='#1b2b3a')
    fig.text(.055,.925,'OFFLINE QA PREVIEW ONLY  •  exact source coordinates retained  •  no basemap / no airspace clearance',fontsize=10,color='#546474')
    fig.text(.735,.88,'NODE IDs  |  '+zone,fontsize=11,weight='bold',color='#1b2b3a')
    y=.847
    step=.021 if len(subset)>25 else .038
    for r in subset:
        fig.text(.75,y,r['code'],fontsize=9,weight='bold',color=colors[r['zone']],va='top')
        y-=step
    fig.text(.055,.065,f'{len(subset)} nodes in this panel. Labels: SHORT IDs ONLY. Full names remain in GIS attributes.',fontsize=9,color='#596b78')
    target=OUT/f'LABEL_QA_{zone}_SHORT_IDS_ONLY_OFFLINE.png'
    fig.savefig(target,dpi=180,facecolor='white')
    plt.close(fig)
    print(target)
