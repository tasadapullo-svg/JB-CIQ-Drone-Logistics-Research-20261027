# -*- coding: utf-8 -*-
"""Generate an openable map-only QGZ by adapting the verified project template.
For editable A3 print layouts, run 02_QGIS322_BUILD_STYLES_LAYOUTS.py from QGIS.
This script uses lxml+fiona and does not require a QGIS installation.
"""
from pathlib import Path
import zipfile, copy, uuid, re
from lxml import etree as ET
import fiona
ROOT=Path(__file__).resolve().parents[1]
GPKG=ROOT/'CIQ_AB_NewA_v3.gpkg'
OUTPUT=ROOT/'CIQ_AB_NewA_v3.qgz'
TEMPLATE=ROOT/'seed'/'v2_render_template.qgs'
if not TEMPLATE.is_file():raise FileNotFoundError(TEMPLATE)
root=ET.parse(str(TEMPLATE)).getroot()
root.attrib['projectname']='CIQ_AB_NewA_v3_NO_A11_WITH_UAV_NOMINAL_REACH'

layer_changes={
 'A_new_11_evidence_nodes':'A_new_10_evidence_nodes',
 'A_new_7_demand_references':'A_new_6_demand_references',
 'A_new_12_unapproved_air_lines':'A_new_11_unapproved_air_lines'
}
rename_phrases={'A01–A11':'A01–A10','A01-A11':'A01-A10','A10–A11':'A10','A10-A11':'A10',
 '12 straight':'11 straight','A04–A08 A10–A11':'A04–A08 A10',
 'Perling–Bukit Indah':'Bukit Indah A09–A10'}
for ml in root.xpath('./projectlayers/maplayer'):
    src=ml.find('datasource')
    if src is None:continue
    old=src.text or ''
    if 'CIQ_AB_NewA_v2.gpkg' in old:
        old=old.replace('CIQ_AB_NewA_v2.gpkg','CIQ_AB_NewA_v3.gpkg')
        for key,val in layer_changes.items():old=old.replace('layername='+key,'layername='+val)
        src.text=old
    name=ml.find('layername')
    if name is not None:
        for a,b in rename_phrases.items(): name.text=(name.text or '').replace(a,b)
    # Keep the QGIS map canvas tidy even at regional scale; full labels in detail layout are generated by PyQGIS.
    if ml.find('labeling') is not None:
        for txt in ml.xpath('./labeling/settings/text-style'):
            txt.set('fontFamily','Noto Sans');txt.set('fontWeight','50');txt.set('fontSize','7')
            for buff in txt.xpath('./text-buffer'):
                buff.set('bufferSize','0.6')
                buff.set('bufferSizeUnits','MM')
    if name is not None and 'A04–A08' in name.text:
        name.text='A NEW | A04–A08 and A10 demand references (NOT landing pads)'

tr=root.find('layer-tree-group')
for sub in tr.xpath('.//layer-tree-layer'):
    for key in ['source','name']:
        v=sub.get(key,'')
        v=v.replace('CIQ_AB_NewA_v2.gpkg','CIQ_AB_NewA_v3.gpkg')
        for old,new in layer_changes.items():v=v.replace('layername='+old,'layername='+new)
        for a,b in rename_phrases.items():v=v.replace(a,b)
        if 'A04–A08' in v and key=='name':v='A NEW | A04–A08 and A10 demand references (NOT landing pads)'
        sub.set(key,v)
for g in tr.xpath('./layer-tree-group'):
    n=g.get('name','')
    for a,b in rename_phrases.items():n=n.replace(a,b)
    g.set('name',n)

reference_ml=next(x for x in root.xpath('./projectlayers/maplayer') if 'WMP228 | two historical' in (x.findtext('layername') or ''))
reference_node=next(x for x in tr.xpath('.//layer-tree-layer') if 'WMP228 | two historical' in x.get('name',''))
parent=reference_node.getparent()
fgroup=ET.Element('layer-tree-group',name='03 | UAV technical return-radius screens (NOT legal authorization)',expanded='1',checked='Qt::Checked')
ET.SubElement(fgroup,'customproperties').append(ET.Element('Option'))
# group moved before WMP boundary group for coverage under the outlines
tr.insert(2,fgroup)
plans=[
 ('reach_DJI_A_WMP_screen','A | DJI 5.6 km return-radius outside TWO WMP historical refs',True,'49,188,183,50','36,158,160,150'),
 ('reach_DJI_B_WMP_screen','B | DJI 5.6 km return-radius screened geometry',True,'49,188,183,50','36,158,160,150'),
 ('reach_WING_A_WMP_screen','A | Wingcopter 32.2 km return-radius (toggle ON)',False,'183,137,215,25','133,91,175,190'),
 ('reach_WING_B_WMP_screen','B | Wingcopter 32.2 km return-radius (toggle ON)',False,'183,137,215,25','133,91,175,190'),
 ('reach_DJI_A_nominal','A | DJI unmasked reference (toggle ON)',False,'255,255,255,0','49,188,183,170'),
 ('reach_DJI_B_nominal','B | DJI unmasked reference (toggle ON)',False,'255,255,255,0','49,188,183,170'),
 ('reach_WING_A_nominal','A | Wingcopter unmasked reference (toggle ON)',False,'255,255,255,0','133,91,175,190'),
 ('reach_WING_B_nominal','B | Wingcopter unmasked reference (toggle ON)',False,'255,255,255,0','133,91,175,190')]
for layerid,label,visible,fill,outline in plans:
    with fiona.open(GPKG,layer=layerid) as obj: bounds=obj.bounds
    node=copy.deepcopy(reference_node)
    node.set('name',label);node.set('source','./CIQ_AB_NewA_v3.gpkg|layername='+layerid)
    node.set('id','CIQ_V3_'+layerid)
    node.set('checked','Qt::Checked' if visible else 'Qt::Unchecked')
    fgroup.append(node)
    ml=copy.deepcopy(reference_ml)
    ml.find('id').text='CIQ_V3_'+layerid
    ml.find('layername').text=label
    ml.find('datasource').text='./CIQ_AB_NewA_v3.gpkg|layername='+layerid
    ex=ml.find('extent')
    if ex is not None:
        for k,v in zip(['xmin','ymin','xmax','ymax'],bounds):
            if ex.find(k) is not None:ex.find(k).text=str(v)
    renderer=ml.find('renderer-v2')
    for item in renderer.xpath('.//Option[@name="color"]|.//Option[@name="outline_color"]'):
        item.set('value',fill if item.get('name')=='color' else outline)
    for item in renderer.xpath('.//prop[@k="color"]|.//prop[@k="outline_color"]'):
        item.set('v',fill if item.get('k')=='color' else outline)
    for item in renderer.xpath('.//Option[@name="style"]|.//prop[@k="style"]'):
        item.set('value' if item.tag=='Option' else 'v','solid' if not fill.endswith(',0') else 'no')
    for item in renderer.xpath('.//Option[@name="outline_style"]|.//prop[@k="outline_style"]'):
        item.set('value' if item.tag=='Option' else 'v','solid' if visible else 'dash')
    root.find('projectlayers').append(ml)

# Store explicitly-reordered layers to make base at bottom and points on top.
lo=root.find('layerorder')
if lo is not None:
    for child in list(lo):lo.remove(child)
    groups=tr.findall('layer-tree-group')
    for g in reversed(groups):
        for layernode in reversed(g.findall('layer-tree-layer')):
            ET.SubElement(lo,'layer',id=layernode.get('id'))

# Checked groups: no A11 in any spatial layer and no Perling view extent.
assert 'A_new_11_evidence_nodes' not in str(ET.tostring(root,encoding='unicode'))
qgs=ET.tostring(root,encoding='utf-8',xml_declaration=True,pretty_print=True)
with zipfile.ZipFile(OUTPUT,'w',zipfile.ZIP_DEFLATED) as z:z.writestr('CIQ_AB_NewA_v3.qgs',qgs)
with zipfile.ZipFile(OUTPUT) as z:
 rr=ET.fromstring(z.read('CIQ_AB_NewA_v3.qgs'))
 assert len(rr.xpath('./projectlayers/maplayer'))>=len(plans)
print('Created QGZ starter (not QGIS-runtime tested):',OUTPUT,'bytes=',OUTPUT.stat().st_size)
